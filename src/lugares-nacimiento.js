export function capitalDepartamentoColombia(departamento) {
  return CAPITAL_DEPARTAMENTO[normalizar(departamento)] || '';
}

export function capitalPais(pais) {
  return CAPITAL_PAIS[normalizar(pais)] || '';
}

export function variantesPais(pais) {
  const n = normalizar(pais);
  const base = ALIASES_PAIS[n] || [pais];
  return [...new Set([pais, ...base].map(normalizar).filter(Boolean))];
}

export function esColombia(pais) {
  return normalizar(pais) === 'COLOMBIA';
}
